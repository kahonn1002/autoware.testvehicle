"""Convert a CarMaker TestRun into an Autoware map, scenario and launch profile.

Example:
  ros2 run autoware_carmaker_launch testrun_to_autoware FS_autonomous_Sprint_LTS \\
      --project /home/klee/project/Carmaker_proj/FSAI_LTS_2026_CM15_Autoware --build
"""

import argparse
import json
