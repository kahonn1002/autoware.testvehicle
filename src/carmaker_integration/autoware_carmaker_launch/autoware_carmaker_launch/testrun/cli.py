INTEGRATION = Path("src") / "carmaker_integration"
LAUNCH_PACKAGE = INTEGRATION / "autoware_carmaker_launch"


class ConversionError(RuntimeError):
    pass


def find_workspace(explicit):
    candidates = [Path(explicit)] if explicit else []
    if os.environ.get("AUTOWARE_TESTVEHICLE_ROOT"):
        candidates.append(Path(os.environ["AUTOWARE_TESTVEHICLE_ROOT"]))
    candidates.extend([Path.cwd(), *Path.cwd().parents, *Path(__file__).resolve().parents])
    for candidate in candidates:
        if (candidate / LAUNCH_PACKAGE).is_dir():
            return candidate.resolve()
    raise ConversionError("Autoware workspace not found; pass --workspace")


def resolve_testrun(testrun, project):
    path = Path(testrun)
    if not path.is_file() and project:
        path = Path(project) / "Data" / "TestRun" / testrun
    if not path.is_file():
        raise ConversionError(f"TestRun not found: {testrun} (pass --project or a file path)")
    path = path.resolve()
    if project is None:
        data = next((parent for parent in path.parents if parent.name == "Data"), None)
        if data is None:
            raise ConversionError("Cannot infer the CarMaker project; pass --project")
        project = data.parent
    return path, Path(project).resolve()


def resolve_road(testrun, testrun_path, project, carmaker_home):
    name = testrun.get("Road.FName")
    if name:
        for root in (project, carmaker_home):
            candidate = Path(root) / "Data" / "Road" / name
            if candidate.is_file():
                return candidate
        raise ConversionError(f"Road file {name} not found in {project}/Data/Road")
    if "Road.nLinks" in testrun or "Road.FileIdent" in testrun:
        return testrun_path
    raise ConversionError("TestRun has neither Road.FName nor an embedded road")


def select_route(road, requested, testrun):
    routes = road.routes()
    if requested is None:
        route = route_object(testrun)
    elif requested.isdigit() and int(requested) in routes:
        route = int(requested)
    else:
        route = next((key for key, name in routes.items() if name == requested), None)
    if route not in routes:
        listed = ", ".join(f"{name} ({key})" for key, name in routes.items())
        raise ConversionError(f"Route {requested or route} not in road; available: {listed}")
    return route, routes[route]


def speed_lookup(speeds, offset, cap):
    """Last speed limit (m/s) starting at or before `offset`, in km/h, capped."""
    active = [speed for speed, start in speeds if start <= offset + 1e-6 and speed > 0.0]
    return min(cap, active[-1] * 3.6) if active else cap


def check_target(path, force, what):
    if not path.exists():
        return
    if not profiles.is_generated(path):
        raise ConversionError(f"{what} {path} exists and was not generated by this tool; "
                              "choose another --name")
    if not force:
        raise ConversionError(f"{what} {path} exists; pass --force to regenerate it")


def parse_args(argv):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("testrun", help="TestRun file, or name under <project>/Data/TestRun")
    parser.add_argument("--project", help="CarMaker project (default: inferred from the TestRun path)")
    parser.add_argument("--name", help="map and profile name (default: from the TestRun name)")
    parser.add_argument("--workspace", help="Autoware workspace (default: auto-detected)")
    parser.add_argument("--carmaker-home", help="CarMaker installation with Python/IPGRoad")
    parser.add_argument("--mode", choices=("auto", "corridor", "network"), default="auto",
                        help="corridor: one route bounded by cones/pylons; network: all lanes")
    parser.add_argument("--boundary", choices=("auto", "cones", "pylons", "path"), default="auto",
                        help="corridor boundary source")
    parser.add_argument("--route", help="ego route name or object id (default: Vehicle.Routing)")
    parser.add_argument("--base-profile", help="profile providing vehicle/sensor/interface settings")
    parser.add_argument("--max-speed-kmh", type=float, default=20.0,
                        help="cap for lanelet speed limits (actuation maps are uncalibrated)")
    parser.add_argument("--spacing", type=float, default=1.0, help="boundary sample spacing [m]")
    parser.add_argument("--chunk-length", type=float, default=20.0, help="lanelet length [m]")
    parser.add_argument("--goal-margin", type=float, default=10.0,
                        help="goal distance before the route end (or behind the start on loops)")
    parser.add_argument("--cone-margin", type=float, default=0.15,
                        help="inset of the corridor boundary from cone centres [m]")
    parser.add_argument("--param", action="append", default=[], metavar="NAME=VALUE",
                        help="override a $NAME named value of the TestRun")
    parser.add_argument("--no-validate", action="store_true", help="skip the Lanelet2 routing check")
    parser.add_argument("--force", action="store_true", help="regenerate an existing conversion")
    parser.add_argument("--build", action="store_true", help="colcon build the integration afterwards")
    parser.add_argument("--launch", action="store_true", help="build, then start Autoware with the profile")
    args = parser.parse_args(argv)
    for name in ("max_speed_kmh", "spacing", "chunk_length", "goal_margin"):
        value = getattr(args, name)
        if not math.isfinite(value) or value <= 0:
            parser.error(f"--{name.replace('_', '-')} must be positive")
    if args.name and not profiles.NAME_PATTERN.match(args.name):
        parser.error("--name must use lowercase letters, digits and underscores")
    return args


def convert(args):
    workspace = find_workspace(args.workspace)
    testrun_path, project = resolve_testrun(args.testrun, args.project)
    testrun = InfoFile.read(testrun_path, parse_named_values(args.param))
    carmaker_home = find_carmaker_home(args.carmaker_home)
    road_path = resolve_road(testrun, testrun_path, project, carmaker_home)
    try:
        road = open_road(road_path, carmaker_home)
    except RoadError as error:
        creator = testrun.get("FileCreator", "an unknown CarMaker version")
        raise ConversionError(
            f"{error}\nThe TestRun was saved by {creator}; IPGRoad from {carmaker_home.name} "
            "could not read its road. Open and save it once in CarMaker 15 to migrate it, "
            "then convert again.") from error
    route, route_name = select_route(road, args.route, testrun)
    start = ego_start(testrun, route)
    name = args.name or profiles.default_name(testrun_path)
    warnings = []

    profile_dir = workspace / LAUNCH_PACKAGE / "config" / "profiles"
    available = profiles.load_profiles(profile_dir)
    hand_written = {key: value for key, value in available.items()
                    if value.get("generated_by") != profiles.GENERATOR}
    vehicle = testrun.get("Vehicle", "")
    base_name = profiles.select_base_profile(vehicle, args.base_profile, hand_written)
    base = hand_written[base_name]
    vehicle_path = vehicle_file(project, vehicle, carmaker_home)
    geometry = vehicle_geometry(InfoFile.read(vehicle_path)) if vehicle_path else None
    if geometry is None:
        warnings.append(f"CarMaker vehicle '{vehicle}' geometry unavailable; not compared")
    differences = profiles.compare_vehicle(
        geometry, profiles.vehicle_info(workspace / INTEGRATION, base["vehicle_model"]))
    for item in differences:
        warnings.append(f"{base['vehicle_model']} {item['parameter']} = {item['autoware']} but the "
                        f"CarMaker vehicle gives {item['carmaker']}")

    objects = locate_traffic(road, traffic_objects(testrun), warnings)
    cones = [(item.position[0], item.position[1], item.side) for item in objects
             if item.kind == "cone" and item.side and item.position_type == "Route"
             and item.route == route]
    gates = route_gates(road, route)
    route_paths = road.route_paths(route)
    user_paths = any(road.path_info(path).kind == "UserPath" for path, _, _ in route_paths)
    cone_rows = min(sum(1 for *_, side in cones if side == row) for row in (1, -1))
    mode = args.mode
    if mode == "auto":
        mode = "corridor" if len(gates) >= 2 or cone_rows >= 4 or user_paths else "network"
    boundary = args.boundary
    if boundary == "auto":
        boundary = "pylons" if len(gates) >= 2 else "cones" if cone_rows >= 4 else "path"

    length = road.route_length(route)
    loop = road.route_loop(route)
    lmap = LaneletMap()
    if mode == "corridor":
        if boundary == "pylons":
            profile = PylonProfile(gates)
        elif boundary == "cones":
            profile = ConeProfile(cones, length, loop is not None, args.cone_margin)
        else:
            profile = path_profile
        route_speeds = road.path_speeds([path for path, _, _ in route_paths])
        corridor = build_corridor(
            lmap, road, route, profile, boundary, args.spacing, args.chunk_length,
            lambda s: speed_lookup(route_speeds, s, args.max_speed_kmh), {"cm_route": route})
        lanelets, warnings = corridor.lanelets, warnings + corridor.warnings
    else:
        cache = {}

        def speed_at(path, offset):
            if path not in cache:
                cache[path] = road.path_speeds([path])
            return speed_lookup(cache[path], offset, args.max_speed_kmh)
        network = build_network(lmap, road, args.spacing, args.chunk_length, speed_at,
                                [path for path, _, _ in route_paths])
        lanelets, warnings = network.lanelets(), warnings + network.warnings
        missing = [path for path, _, _ in route_paths if path not in network.paths
                   and not is_lane_change(road.path_info(path))]
        if missing:
            warnings.append(f"Ego route paths without lanelets: {missing}")

    # CMNode publishes CarMaker's Fr1 origin; the interface shifts it to base_link.
    first = route_pose(road, route, start.s, start.t)
    yaw = first.yaw = first.yaw + start.yaw_offset
    dx, dy, dz = profiles.interface_offset(workspace / INTEGRATION, base)
    initial = Pose(first.x + dx * math.cos(yaw) - dy * math.sin(yaw),
                   first.y + dx * math.sin(yaw) + dy * math.cos(yaw), first.z + dz, yaw)
    goal_s = goal_station(length, start.s, loop is not None, args.goal_margin, args.chunk_length)
    goal = route_pose(road, route, goal_s)
    waypoints = []
    if mode == "network":
        pinned = {path for path, item in network.paths.items() if item.exact}
        waypoints = [route_pose(road, route, s) for s in waypoint_stations(
            route_paths, pinned, start.s % length, goal_s, length, loop is not None)]

    map_dir = workspace / "maps" / name
    profile_path = profile_dir / f"{name}.yaml"
    if map_dir.exists() and not (map_dir / "scenario.yaml").exists():
        raise ConversionError(f"{map_dir} exists and was not generated by this tool; choose another --name")
    check_target(map_dir / "scenario.yaml", args.force, "Scenario")
    check_target(profile_path, args.force, "Profile")
    map_dir.mkdir(parents=True, exist_ok=True)
    stats = lmap.write(map_dir / "lanelet2_map.osm", generator=profiles.GENERATOR)
    points = surface_points(lmap, lanelets) + object_points(objects)
    for x, y, z in gate_pylons(road, route, gates):
        points.extend(column_points(x, y, z, CONE_HEIGHT))
    points = thin(points)
    write_pcd(map_dir / "pointcloud_map.pcd", points)
    write_projector(map_dir / "map_projector_info.yaml")
    validation = ({"skipped": "--no-validate"} if args.no_validate
                  else validate_map(map_dir / "lanelet2_map.osm", initial, goal, waypoints))
    driven = (goal_s - start.s) % length if loop is not None else goal_s - start.s
    validation["carmaker_route_m"] = round(driven, 1)

    map_path = f"maps/{name}"
    scenario = {
        "generated_by": profiles.GENERATOR,
        "source": {
            "testrun": str(testrun_path), "testrun_sha256": sha256(testrun_path),
            "road": str(road_path), "road_sha256": sha256(road_path),
            "carmaker_home": str(carmaker_home), "named_values": dict(testrun.named_values),
        },
        "conversion": {
            "mode": mode, "boundary": boundary if mode == "corridor" else None,
            "route": {"object_id": route, "name": route_name, "length_m": round(length, 3),
                      "closed": loop is not None},
            "route_t_reference": "driving path",
            "spacing_m": args.spacing, "chunk_length_m": args.chunk_length,
            "max_speed_kmh": args.max_speed_kmh, "map": stats, "pcd_points": len(points),
        },
        "autoware": {
            "profile": name, "base_profile": base_name, "map_path": map_path,
            "initial_pose": initial.as_dict(), "initial_pose_fr1": first.as_dict(),
            "goal": goal.as_dict(), "goal_route_s": round(goal_s, 3),
            "waypoints": [pose.as_dict() for pose in waypoints],
        },
        "vehicle": {"carmaker": vehicle, "geometry": geometry, "differences": differences},
        "traffic_objects": {
            "cones": sum(1 for item in objects if item.kind == "cone"),
            "static": sum(1 for item in objects if item.kind == "static"),
            "dynamic": [{"name": item.name, "template": item.template,
                         "pose": item.pose.as_dict() if item.pose else None}
                        for item in objects if item.kind == "dynamic"],
        },
        "validation": validation,
        "warnings": warnings,
    }
    header = (f"# Generated by {profiles.GENERATOR} from {testrun_path.name}; "
              "regenerate instead of editing.\n")
    write_yaml(map_dir / "scenario.yaml", scenario, header)
    write_yaml(profile_path, profiles.generated_profile(base_name, base, map_path, testrun_path), header)
    return {"name": name, "workspace": workspace, "map_dir": map_dir, "profile": profile_path,
            "scenario": scenario}


def build(workspace):
    env = dict(os.environ, PATH="/usr/bin:/bin:" + os.environ.get("PATH", ""))
    colcon = shutil.which("colcon", path=env["PATH"])
    if colcon is None:
        raise ConversionError("colcon not found; source /opt/ros/humble/setup.bash")
    command = [colcon, "build", "--symlink-install", "--base-paths", str(INTEGRATION),
               "--packages-select", "autoware_carmaker_interface", "autoware_carmaker_launch"]
    print("+ " + " ".join(shlex.quote(part) for part in command), flush=True)
    subprocess.run(command, cwd=workspace, env=env, check=True)


def launch_command(workspace, name):
    return (f"cd {shlex.quote(str(workspace))} && source /opt/ros/humble/setup.bash && "
            f"source install/setup.bash && ros2 launch autoware_carmaker_launch "
            f"carmaker.launch.py profile:={name}")


def main(argv=None):
    args = parse_args(argv)
    try:
        result = convert(args)
    except (ConversionError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    scenario = result["scenario"]
    conversion, validation = scenario["conversion"], scenario["validation"]
    print(f"Converted {Path(scenario['source']['testrun']).name} -> {result['map_dir']}")
    print(f"  mode={conversion['mode']} boundary={conversion['boundary']} "
          f"route={conversion['route']['name']} ({conversion['route']['length_m']} m"
          f"{', loop' if conversion['route']['closed'] else ''})")
    print(f"  lanelets={conversion['map']['lanelets']} pcd_points={conversion['pcd_points']} "
          f"profile={result['profile']}")
    print("  validation: " + json.dumps(validation))
    for warning in scenario["warnings"]:
        print(f"  warning: {warning}")
    if validation.get("passed") is False:
        print("error: the converted map does not route from the ego start to the goal", file=sys.stderr)
        return 1
    if args.build or args.launch:
        try:
            build(result["workspace"])
        except (ConversionError, subprocess.CalledProcessError) as error:
            print(f"error: build failed: {error}", file=sys.stderr)
            return 3
    command = launch_command(result["workspace"], result["name"])
    if args.launch:
        os.execvp("bash", ["bash", "-c", command])
    if not args.build:
        print("Next: rebuild so the new profile is installed (or rerun with --build).")
    print(f"Run Autoware:  {command}")
    print(f"Run CarMaker:  load TestRun {Path(scenario['source']['testrun']).name}, start it; "
          "the route is set automatically once localization is initialized.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
